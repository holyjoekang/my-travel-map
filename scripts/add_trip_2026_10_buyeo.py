def blocks(text):
    """한 줄 표기 → 블록. '#' 제목 · '~' 부제 · '##' 소제목 · '-' 목록 · '|' 표 · '>' 인용 · '!' 일러두기 · 나머지 문단"""
    out = []
    for line in text.splitlines():
        if not line.strip():
            continue
        tag, body = (line[:2].strip(), line[2:].strip()) if line[:2] in ("##", "- ", "| ", "> ", "! ", "~ ", "# ") \
            else ("p", line.strip())
        if tag in ("-", "|") and out and out[-1]["t"] == tag:
            out[-1]["items"].append([c.strip() for c in body.split("|")] if tag == "|" else body)
        elif tag in ("-", "|"):
            out.append({"t": tag, "items": [[c.strip() for c in body.split("|")] if tag == "|" else body]})
        else:
            out.append({"t": tag, "text": body})
    return out


